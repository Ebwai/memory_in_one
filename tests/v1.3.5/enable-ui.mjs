import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { createRequire } from 'node:module';
import { _electron } from 'playwright-core';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
const require = createRequire(import.meta.url);
const root = resolve('tests/v1.3.5/artifacts/ui-' + Date.now());
await mkdir(join(root, 'codex'), { recursive: true });
const env = { ...process.env, WORKSPACE_CLIENT_DIRECTORY: root, WORKSPACE_SETUP_HIDDEN: '1', CODEX_HOME: join(root, 'codex') };
delete env.ELECTRON_RUN_AS_NODE;
const app = await _electron.launch({ executablePath: process.env.WORKSPACE_TEST_DESKTOP ?? require('electron'), args: process.env.WORKSPACE_TEST_DESKTOP ? [] : ['apps/desktop/dist/host/workspace-main.js'], env });
let client;
try {
  const page = await app.firstWindow();
  await page.getByRole('button', { name: '创建新工作空间', exact: true }).click();
  await page.getByRole('button', { name: '确认创建', exact: true }).click();
  await page.getByRole('button', { name: '03 MCP', exact: true }).waitFor();
  const legacySpace = JSON.parse(await readFile(join(root, 'binding.json'), 'utf8'));
  await writeFile(join(root, 'spaces.json'), JSON.stringify(legacySpace));
  await page.getByRole('button', { name: '03 MCP', exact: true }).click();
  await page.getByRole('button', { name: '一键开启 MCP', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Codex 用户级 MCP 已配置' }).waitFor();
  const configuration = await readFile(join(root, 'codex/config.toml'), 'utf8');
  assert.ok(configuration.includes('WORKSPACE_MCP_DESCRIPTOR'));
  client = new Client({ name: 'One click QA', version: '1.0' });
  await client.connect(new StdioClientTransport({ command: process.env.WORKSPACE_TEST_DESKTOP ?? process.execPath, args: [process.env.WORKSPACE_TEST_MCP_ENTRY ?? resolve('apps/mcp/protocol/main.mjs')], env: { ...process.env, ...(process.env.WORKSPACE_TEST_DESKTOP ? { ELECTRON_RUN_AS_NODE: '1' } : {}), WORKSPACE_MCP_DESCRIPTOR: join(root, 'codex-mcp-broker.json') } }));
  const names = (await client.listTools()).tools.map(tool => tool.name);
  assert.ok(names.includes('todo_create') && names.includes('note_query') && names.includes('workspace_list'));
  const list = await client.callTool({ name: 'workspace_list', arguments: {} });
  const spaces = JSON.parse(list.content[0].text);
  assert.equal(spaces.length, 1);
  const args = { workspaceId: spaces[0].workspaceId, operationId: 'one-click-todo', text: '一键接入创建任务' };
  const created = await client.callTool({ name: 'todo_create', arguments: args });
  assert.equal(JSON.parse(created.content[0].text).status, 'accepted');
  const grants = await page.evaluate(() => window.workspaceSetup.mcp('grants'));
  const grant = grants.find(grant => grant.name === 'Codex 一键接入');
  assert.deepEqual(grant.domains, ['*']);
  assert.ok(grant.actions.includes('delete-unattended') && grant.actions.includes('backup'));
  await page.screenshot({ path: join(root, 'one-click-mcp.png') });
  console.log('PASS actual desktop one-click -> isolated Codex config -> stdio MCP -> full grant -> task creation');
} finally { await client?.close(); await app.close(); }
