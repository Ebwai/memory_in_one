import { test } from 'node:test';
import assert from 'node:assert/strict';
import { _electron } from 'playwright-core';
import { createRequire } from 'node:module';
import { mkdtempSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
test('four management pages and isolated durable workspace switching', { timeout: 90000 }, async () => {
  const require = createRequire(import.meta.url);
  const directory = mkdtempSync(join(tmpdir(), 'workspace-management-'));
  const env = { ...process.env, WORKSPACE_CLIENT_DIRECTORY: directory, WORKSPACE_SETUP_HIDDEN: '1' }; delete env.ELECTRON_RUN_AS_NODE;
  const launch = () => _electron.launch({ executablePath: require('electron'), args: ['apps/desktop/dist/host/workspace-main.js'], env });
  let app = await launch();
  mkdirSync('output/ui-preview', { recursive: true });
  try {
    let page = await app.firstWindow();
    await page.getByRole('button', { name: '创建新工作空间', exact: true }).click();
    await page.getByRole('button', { name: '确认创建', exact: true }).click();
    await page.getByLabel('任务内容', { exact: true }).fill('只属于第一个空间');
    await page.getByLabel('任务内容', { exact: true }).press('Enter');
    await page.getByTestId('captured-todo').waitFor();
    await page.getByRole('button', { name: '工作空间', exact: true }).click();
    const nav = page.getByRole('navigation', { name: '管理导航' });
    await nav.waitFor();
    await nav.getByRole('button', { name: '服务器', exact: false }).click();
    await page.getByRole('heading', { name: /服务器连接拓扑/ }).waitFor();
    assert.equal(await page.getByTestId('workspace-created').isVisible(), false);
    await page.screenshot({ path: 'output/ui-preview/management-server.png' });
    await nav.getByRole('button', { name: '设置', exact: false }).click();
    await page.locator('.app-update').waitFor();
    assert.equal(await page.getByTestId('ssh-settings').isVisible(), false);
    await nav.getByRole('button', { name: 'MCP', exact: false }).click();
    await page.getByTestId('mcp-management').waitFor();
    await nav.getByRole('button', { name: '工作空间', exact: false }).click();
    await page.getByRole('button', { name: '＋ 新建空间', exact: true }).click();
    await page.getByLabel('工作空间名称', { exact: true }).fill('第二个空间');
    await page.getByLabel('本机存放目录', { exact: true }).fill(join(directory, 'second-authority'));
    await page.getByRole('button', { name: '确认创建', exact: true }).click();
    await page.getByTestId('workspace-created').getByRole('heading', { name: /第二个空间/ }).waitFor();
    const spaces = page.getByRole('region', { name: '工作空间列表' });
    await spaces.getByRole('button', { name: /我的工作空间/ }).click();
    await page.getByTestId('workspace-created').getByRole('heading', { name: /我的工作空间/ }).waitFor();
    await page.screenshot({ path: 'output/ui-preview/management-workspace.png' });
    await nav.getByRole('button', { name: '返回工作台', exact: false }).click();
    await page.getByTestId('captured-todo').getByText('只属于第一个空间', { exact: true }).waitFor();
    await page.getByRole('button', { name: '工作空间', exact: true }).click();
    await spaces.getByRole('button', { name: /第二个空间/ }).click();
    await page.getByTestId('workspace-created').getByRole('heading', { name: /第二个空间/ }).waitFor();
    await nav.getByRole('button', { name: '返回工作台', exact: false }).click();
    await page.getByTestId('todo-capture').waitFor();
    assert.equal(await page.getByTestId('captured-todo').count(), 0);
    await app.close(); app = await launch(); page = await app.firstWindow();
    await page.getByTestId('todo-capture').waitFor();
    assert.equal(await page.getByTestId('captured-todo').count(), 0);
    const saved = await page.evaluate(() => window.workspaceSetup.spaces('list'));
    assert.equal(saved.spaces.length, 2);
    assert.equal(saved.binding.workspace.name, '第二个空间');
    await page.getByRole('button', { name: '工作空间', exact: true }).click();
    const recovery = page.getByTestId('workspace-recovery');
    await recovery.getByLabel('恢复到设备').selectOption('server');
    assert.equal(await recovery.getByRole('button', { name: '选择材料与恢复目标', exact: true }).isDisabled(), true);
    await recovery.getByText(/服务器直接恢复暂未实现/).waitFor();
    await recovery.getByLabel('恢复到设备').selectOption('local');
    await app.evaluate(({ ipcMain }) => { ipcMain.removeHandler('workspace:sync'); ipcMain.handle('workspace:sync', () => ({ phase: 'failed', pending: 1, uncertain: 0, conflicts: 0, confirmed: 0, cursor: 0, lastSuccessAt: null, message: '测试：服务器不可达' })); });
    const exp = page.getByTestId('export-scope');
    await exp.getByRole('button', { name: '选择导出范围', exact: true }).click();
    await exp.getByRole('button', { name: '查看所选来源范围', exact: true }).click();
    await exp.getByRole('alert').getByText(/同步尚未完成/).waitFor();
    assert.equal(await exp.getByTestId('export-preview').count(), 0);
  } catch (error) { const page = await app.firstWindow(); console.log(await page.locator('body').innerText()); await page.screenshot({path:'output/ui-preview/management-failure.png'}); throw error; } finally { await app.close(); }
});
