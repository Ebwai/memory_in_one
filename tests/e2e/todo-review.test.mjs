import { test } from "node:test";
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { DatabaseSync } from "node:sqlite";
import { _electron } from "playwright-core";
import { SqliteLocalStore } from "@workspace/adapters";

const require = createRequire(import.meta.url);
test("N16–N20 persisted review, local day changes, stable ordering, details and read failure", { timeout: 120000 }, async () => {
  const directory = mkdtempSync(join(tmpdir(), "workspace-review-"));
  const env = { ...process.env, WORKSPACE_CLIENT_DIRECTORY: directory, WORKSPACE_SETUP_HIDDEN: "1" };
  delete env.ELECTRON_RUN_AS_NODE;
  let application;
  let store;
  let binding;
  let version;
  const longText = "完整任务首行\n" + "需要完整阅读的中文长内容。".repeat(100) + "\n完整任务末尾";
  const launch = () => _electron.launch({ executablePath: require("electron"), args: ["apps/desktop/dist/host/workspace-main.js"], env });
  const database = (run) => {
    const db = new DatabaseSync(binding.replicaPath);
    try { return run(db); } finally { db.close(); }
  };
  const count = () => database((db) => db.prepare("SELECT count(*) AS count FROM pending_operations").get().count);
  async function write(id, payload, deleted = false) {
    store ??= await SqliteLocalStore.open({ databasePath: binding.replicaPath });
    await store.commit({ workspaceId: binding.workspace.workspaceId, domainId: "builtin.todo", recordId: id,
      operationId: "fixture-" + id + (deleted ? "-delete" : ""), kind: deleted ? "delete" : "put", payloadJson: deleted ? null : JSON.stringify(payload) });
  }
  try {
    application = await launch();
    let page = await application.firstWindow();
    await page.getByRole("button", { name: "创建新工作空间", exact: true }).click();
    await page.getByRole("button", { name: "确认创建", exact: true }).click();
    await page.getByText("还没有任务，添加第一条待办吧。", { exact: true }).waitFor();
    await page.getByText("暂无未完成任务", { exact: true }).waitFor();
    binding = JSON.parse(readFileSync(join(directory, "binding.json"), "utf8"));
    version = database((db) => db.prepare("PRAGMA user_version").get().user_version);
    await application.close(); application = undefined;
    const task = (text, createdAt, extra = {}) => ({ text, createdAt, completed: false, ...extra });
    await write("newest", task("最新任务", "2026-10-25T07:00:00Z", { dueDate: "2026-10-25" }));
    await write("long-task", task(longText, "2026-10-25T06:00:00Z"));
    await write("future", task("未来日期也持续显示", "2026-10-25T05:00:00Z", { dueDate: "2026-10-27" }));
    await write("past", task("过去日期也持续显示", "2026-10-25T04:00:00Z", { dueDate: "2026-10-24" }));
    await write("tie-b", task("同时间乙", "2026-10-25T03:00:00Z"));
    await write("tie-a", task("同时间甲", "2026-10-25T03:00:00Z"));
    await write("invalid", task("非法日期不隐藏", "2026-10-25T02:00:00Z", { dueDate: "2026-02-30" }));
    await write("unknown", task("状态待核对", "2026-10-25T01:00:00Z", { completed: "unknown" }));
    await write("done-old", task("较早完成的任务", "2026-10-25T08:00:00Z", { completed: true, completedAt: "2026-10-25T08:00:00Z", dueDate: "2026-10-24" }));
    await write("done-new", task("较晚完成的任务", "2026-10-24T01:00:00Z", { completed: true, completedAt: "2026-10-25T09:00:00Z" }));
    for (let i = 0; i < 24; i++) await write("filler-" + i, task("可滚动任务 " + i, "2026-10-24T01:00:00Z"));
    await write("deleted", {}, true);
    await store.close(); store = undefined;
    const initialCount = count();
    application = await launch(); page = await application.firstWindow();
    await page.getByTestId("todo-capture").waitFor();
    await page.evaluate(() => {
      const original = Date;
      globalThis.__reviewClock = { value: "2026-10-25T12:00:00" };
      globalThis.Date = new Proxy(original, { construct(target, args, newTarget) { return Reflect.construct(target, args.length ? args : [globalThis.__reviewClock.value], newTarget); } });
      window.dispatchEvent(new Event("focus"));
    });
    const unfinished = page.getByTestId("unfinished-todos");
    const row = (id) => page.locator('[data-record-id="' + id + '"]');
    await row("newest").getByText("今天到期", { exact: true }).waitFor();
    await row("past").getByText("已逾期 · 2026-10-24", { exact: true }).waitFor();
    await row("future").getByText("截止 2026-10-27", { exact: true }).waitFor();
    await row("invalid").getByRole("alert").waitFor();
    await row("unknown").getByRole("alert").waitFor();
    const ids = () => unfinished.locator("li").evaluateAll((items) => items.map((item) => item.dataset.recordId));
    const order = await ids();
    assert.deepEqual(order.slice(0, 8), ["newest", "long-task", "future", "past", "tie-a", "tie-b", "invalid", "unknown"]);
    assert.equal(order.length, 32);
    assert.equal(await page.locator('[data-record-id="deleted"]').count(), 0);
    const completed = page.getByTestId("completed-todos");
    assert.equal(await completed.isVisible(), false);
    await page.getByRole("button", { name: "已完成（2）", exact: true }).click();
    assert.deepEqual(await completed.locator("li").evaluateAll((items) => items.map((item) => item.dataset.recordId)), ["done-new", "done-old"]);
    assert.equal(await row("done-old").getByText(/已逾期/).count(), 0);
    const scroll = page.getByTestId("todo-review-scroll");
    await row("done-new").locator("button.todo-open").scrollIntoViewIfNeeded();
    const scrollBefore = await scroll.evaluate((element) => element.scrollTop);
    await row("done-new").locator("button.todo-open").click();
    const details = page.getByTestId("todo-details");
    await details.getByText("未设置", { exact: true }).waitFor();
    await details.getByRole("button", { name: "关闭详情", exact: true }).click();
    assert.equal(await page.getByRole("button", { name: "已完成（2）", exact: true }).getAttribute("aria-expanded"), "true");
    assert.equal(await scroll.evaluate((element) => element.scrollTop), scrollBefore);
    await row("long-task").locator("button.todo-open").click();
    await details.getByText("未设置", { exact: true }).waitFor();
    assert.equal(await details.getByTestId("todo-full-text").innerText(), longText);
    await details.getByRole("button", { name: "关闭详情", exact: true }).click();
    assert.equal(count(), initialCount);
    await page.evaluate(() => { globalThis.__reviewClock.value = "2026-10-26T00:00:01"; });
    // Keep the window open: its own clock check must refresh the calendar label.
    await row("newest").getByText("已逾期 · 2026-10-25", { exact: true }).waitFor({ timeout: 5000 });
    assert.deepEqual(await ids(), order);
    assert.equal(count(), initialCount);
    await row("newest").locator("button.todo-open").click();
    await details.getByTestId("todo-full-text").getByText("最新任务", { exact: true }).waitFor();
    database((db) => db.exec("PRAGMA user_version = 999"));
    await details.getByRole("button", { name: "重新读取任务", exact: true }).click();
    await details.getByRole("alert").getByText(/无法读取最新本机信息/).waitFor();
    assert.equal(await details.getByTestId("todo-full-text").innerText(), "最新任务");
    await details.getByRole("button", { name: "关闭详情", exact: true }).click();
    await page.getByRole("button", { name: "重新读取列表", exact: true }).click();
    await page.getByTestId("todo-list-error").waitFor();
    assert.deepEqual(await ids(), order);
    assert.equal(await page.getByText("暂无未完成任务", { exact: true }).count(), 0);
    database((db) => db.exec("PRAGMA user_version = " + version));
    await page.getByRole("button", { name: "重新读取列表", exact: true }).click();
    await page.getByTestId("todo-list-error").waitFor({ state: "detached" });
    await row("newest").locator("button.todo-open").click();
    await details.getByTestId("todo-full-text").getByText("最新任务", { exact: true }).waitFor();
    await write("newest", null, true); await store.close(); store = undefined;
    const afterDeleteCount = count();
    await details.getByRole("button", { name: "重新读取任务", exact: true }).click();
    await details.getByRole("alert").getByText("这条任务已不存在，请返回列表。", { exact: true }).waitFor();
    assert.equal(await details.getByTestId("todo-full-text").count(), 0);
    await details.getByRole("button", { name: "关闭详情", exact: true }).click();
    assert.equal(await row("newest").count(), 0);
    assert.equal(count(), afterDeleteCount);
    await scroll.evaluate((element) => { element.scrollTop = 0; });
    await page.screenshot({ path: ".build/todo-review.png", fullPage: true });
    await application.close(); application = undefined;
    application = await launch(); page = await application.firstWindow();
    await page.getByRole("button", { name: "已完成（2）", exact: true }).waitFor();
    assert.equal(await page.getByTestId("completed-todos").isVisible(), false);
    assert.equal(count(), afterDeleteCount);
    for (const id of order.filter((id) => id !== "newest")) await write(id, null, true);
    await store.close(); store = undefined;
    const onlyCompletedCount = count();
    await page.getByRole("button", { name: "重新读取列表", exact: true }).click();
    await page.getByText("暂无未完成任务", { exact: true }).waitFor();
    assert.equal(await page.getByText("还没有任务，添加第一条待办吧。", { exact: true }).count(), 0);
    await page.getByRole("button", { name: "已完成（2）", exact: true }).click();
    assert.equal(await page.getByTestId("completed-todos").locator("li").count(), 2);
    assert.equal(count(), onlyCompletedCount);
  } finally {
    if (store) await store.close();
    if (binding && version !== undefined) database((db) => db.exec("PRAGMA user_version = " + version));
    if (application) await application.close();
    assert.equal(dirname(resolve(directory)), resolve(tmpdir()));
    assert.ok(directory.split(/[/\\]/).at(-1)?.startsWith("workspace-review-"));
    rmSync(directory, { recursive: true, force: true });
  }
});
