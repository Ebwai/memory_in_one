import { test } from "node:test";
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { DatabaseSync } from "node:sqlite";
import { _electron } from "playwright-core";
import { SqliteLocalStore } from "@workspace/adapters";

const require = createRequire(import.meta.url);
test("N21–N25 real task editing, dates, completion, guarded deletion, failure and restart", { timeout: 120000 }, async () => {
  const directory = mkdtempSync(join(tmpdir(), "workspace-progress-window-"));
  const env = { ...process.env, WORKSPACE_CLIENT_DIRECTORY: directory, WORKSPACE_SETUP_HIDDEN: "1" };
  delete env.ELECTRON_RUN_AS_NODE;
  let application;
  let binding;
  const launch = () => _electron.launch({ executablePath: require("electron"), args: ["apps/desktop/dist/host/workspace-main.js"], env });
  const database = (run) => { const db = new DatabaseSync(binding.replicaPath); try { db.exec("PRAGMA busy_timeout=5000"); return run(db); } finally { db.close(); } };
  const tasks = () => database((db) => db.prepare("SELECT record_id, deleted, payload_json, last_sequence FROM local_records WHERE domain_id='builtin.todo' ORDER BY record_id").all());
  const pendingCount = () => database((db) => db.prepare("SELECT count(*) AS count FROM pending_operations WHERE domain_id='builtin.todo'").get().count);
  try {
    application = await launch();
    let page = await application.firstWindow();
    await page.getByRole("button", { name: "创建新工作空间", exact: true }).click();
    await page.getByRole("button", { name: "确认创建", exact: true }).click();
    const input = page.getByLabel("任务内容", { exact: true });
    await input.fill("原任务"); await input.press("Enter");
    await page.getByTestId("captured-todo").getByRole("button", { name: "原任务", exact: true }).waitFor();
    await input.fill("另一个任务"); await input.press("Enter");
    await page.getByTestId("captured-todo").getByRole("button", { name: "另一个任务", exact: true }).waitFor();
    binding = JSON.parse(readFileSync(join(directory, "binding.json"), "utf8"));
    const initial = tasks().find((row) => JSON.parse(row.payload_json).text === "原任务");
    const id = initial.record_id;
    const row = () => page.locator('[data-record-id="' + id + '"]');
    const original = JSON.parse(initial.payload_json);
    const details = () => page.getByTestId("todo-details");
    await row().getByRole("button", { name: "原任务", exact: true }).click();
    await details().getByRole("button", { name: "编辑内容", exact: true }).click();
    const editor = details().getByLabel("编辑任务内容", { exact: true });
    assert.equal(await editor.inputValue(), "原任务");
    await editor.fill("取消的修改");
    await details().getByRole("button", { name: "取消编辑", exact: true }).click();
    assert.equal(await details().getByTestId("todo-full-text").innerText(), "原任务");
    assert.equal(pendingCount(), 2);
    await details().getByRole("button", { name: "编辑内容", exact: true }).click();
    await editor.fill("  "); await details().getByRole("button", { name: "保存修改", exact: true }).click();
    await details().getByRole("alert").getByText(/不能保存纯空白/).waitFor();
    assert.equal(await editor.inputValue(), "  ");
    await editor.fill("修改后的中文\n仍是一条任务");
    await details().getByRole("button", { name: "保存修改", exact: true }).click();
    await details().getByTestId("todo-full-text").getByText("修改后的中文\n仍是一条任务", { exact: true }).waitFor();
    assert.equal(JSON.parse(tasks().find((task) => task.record_id === id).payload_json).createdAt, original.createdAt);
    await details().getByRole("button", { name: "设置截止日期", exact: true }).click();
    await details().getByLabel("截止日期选择", { exact: true }).fill("2020-01-01");
    await details().getByRole("button", { name: "保存修改", exact: true }).click();
    await details().getByText("已逾期 · 2020-01-01", { exact: true }).waitFor();
    await details().getByRole("button", { name: "设置截止日期", exact: true }).click();
    await details().getByRole("button", { name: "清除日期", exact: true }).click();
    await details().getByRole("button", { name: "取消编辑", exact: true }).click();
    assert.equal(JSON.parse(tasks().find((task) => task.record_id === id).payload_json).dueDate, "2020-01-01");
    await details().getByRole("button", { name: "设置截止日期", exact: true }).click();
    await details().getByRole("button", { name: "清除日期", exact: true }).click();
    await details().getByRole("button", { name: "保存修改", exact: true }).click();
    await details().getByText("未设置", { exact: true }).waitFor();
    await details().getByRole("button", { name: "标记完成", exact: true }).click();
    await details().getByRole("button", { name: "恢复未完成", exact: true }).waitFor();
    const firstCompletion = JSON.parse(tasks().find((task) => task.record_id === id).payload_json).completedAt;
    assert.ok(firstCompletion);
    await details().getByRole("button", { name: "编辑内容", exact: true }).click();
    await editor.fill("已完成也能编辑"); await details().getByRole("button", { name: "保存修改", exact: true }).click();
    await details().getByTestId("todo-full-text").getByText("已完成也能编辑", { exact: true }).waitFor();
    assert.equal(JSON.parse(tasks().find((task) => task.record_id === id).payload_json).completedAt, firstCompletion);
    await details().getByRole("button", { name: "关闭详情", exact: true }).click();
    await page.getByRole("button", { name: "已完成（1）", exact: true }).click();
    await row().getByRole("checkbox", { name: "已完成任务", exact: true }).click();
    await row().getByRole("checkbox", { name: "未完成任务", exact: true }).waitFor();
    assert.equal(Object.hasOwn(JSON.parse(tasks().find((task) => task.record_id === id).payload_json), "completedAt"), false);
    const beforeToggle = pendingCount();
    await row().getByRole("checkbox", { name: "未完成任务", exact: true }).click();
    await page.getByRole("button", { name: "已完成（1）", exact: true }).waitFor();
    assert.equal(pendingCount(), beforeToggle + 1);
    assert.notEqual(JSON.parse(tasks().find((task) => task.record_id === id).payload_json).completedAt, firstCompletion);
    await row().getByRole("button", { name: "已完成也能编辑", exact: true }).click();
    await details().getByRole("button", { name: "编辑内容", exact: true }).click();
    await editor.fill("失败时应保留文字");
    database((db) => db.exec("CREATE TRIGGER fail_progress_window BEFORE INSERT ON pending_operations WHEN NEW.domain_id = 'builtin.todo' BEGIN SELECT RAISE(ABORT, 'save failure'); END"));
    await details().getByRole("button", { name: "保存修改", exact: true }).click();
    await details().getByTestId("todo-progress-status").getByText(/本机保存失败/).waitFor();
    assert.equal(await editor.inputValue(), "失败时应保留文字");
    database((db) => db.exec("DROP TRIGGER fail_progress_window"));
    await editor.fill("恢复后保存"); await details().getByRole("button", { name: "保存修改", exact: true }).click();
    await details().getByTestId("todo-full-text").getByText("恢复后保存", { exact: true }).waitFor();
    await details().getByRole("button", { name: "编辑内容", exact: true }).click();
    await editor.fill("待确认后保存");
    const version = database((db) => db.prepare("PRAGMA user_version").get().user_version);
    database((db) => db.exec("PRAGMA user_version = 999"));
    await details().getByRole("button", { name: "保存修改", exact: true }).click();
    await details().getByRole("button", { name: "核对原任务操作", exact: true }).waitFor();
    assert.equal(await editor.getAttribute("readonly"), "");
    assert.equal(await details().getByRole("button", { name: "取消编辑", exact: true }).isDisabled(), true);
    await details().getByRole("button", { name: "关闭详情", exact: true }).click();
    assert.equal(await row().getByRole("checkbox").isDisabled(), true);
    database((db) => db.exec("PRAGMA user_version = " + version));
    const other = page.getByTestId("captured-todo").filter({ has: page.getByRole("button", { name: "另一个任务", exact: true }) });
    await other.getByRole("checkbox", { name: "未完成任务", exact: true }).click();
    await other.getByRole("checkbox", { name: "已完成任务", exact: true }).waitFor();
    await other.getByRole("checkbox", { name: "已完成任务", exact: true }).click();
    await other.getByRole("checkbox", { name: "未完成任务", exact: true }).waitFor();
    assert.equal(await row().getByRole("checkbox").isDisabled(), true);
    await row().getByRole("button", { name: "恢复后保存", exact: true }).click();
    assert.equal(await editor.inputValue(), "待确认后保存");
    await details().getByRole("button", { name: "核对原任务操作", exact: true }).click();
    await details().getByTestId("todo-full-text").getByText("待确认后保存", { exact: true }).waitFor();
    await details().getByRole("button", { name: "编辑内容", exact: true }).click();
    await editor.fill("不能覆盖另一端的新版本");
    const external = await SqliteLocalStore.open({ databasePath: binding.replicaPath });
    try {
      const current = await external.readRecord({ workspaceId: binding.workspace.workspaceId, domainId: "builtin.todo", recordId: id });
      await external.commit({ workspaceId: binding.workspace.workspaceId, domainId: "builtin.todo", recordId: id, operationId: "external-progress-change", kind: "put", payloadJson: JSON.stringify({ ...current.payload, dueDate: "2030-01-01" }) });
    } finally { await external.close(); }
    await details().getByRole("button", { name: "保存修改", exact: true }).click();
    await details().getByTestId("todo-progress-status").getByText(/其他操作修改|依据已变化/).waitFor();
    assert.equal(await editor.inputValue(), "不能覆盖另一端的新版本");
    assert.equal(JSON.parse(tasks().find((task) => task.record_id === id).payload_json).text, "待确认后保存");
    await details().getByRole("button", { name: "取消编辑", exact: true }).click();
    await details().getByRole("button", { name: "编辑内容", exact: true }).click();
    await editor.fill("关闭窗口前的草稿");
    await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close());
    await page.getByRole("button", { name: "取消操作", exact: true }).click();
    assert.equal(await editor.inputValue(), "关闭窗口前的草稿");
    await details().getByRole("button", { name: "取消编辑", exact: true }).click();
    const beforeDelete = tasks();
    await details().getByRole("button", { name: "删除任务", exact: true }).click();
    await details().getByTestId("todo-delete-confirm").getByText("待确认后保存", { exact: true }).waitFor();
    await details().getByRole("button", { name: "取消删除", exact: true }).click();
    assert.deepEqual(tasks(), beforeDelete);
    await details().getByRole("button", { name: "删除任务", exact: true }).click();
    await details().getByText("确认删除这条任务？删除后没有回收站或撤销删除入口。", { exact: true }).waitFor();
    await details().getByRole("button", { name: "确认删除任务", exact: true }).click();
    await details().waitFor({ state: "detached" });
    assert.equal(await row().count(), 0);
    assert.equal(tasks().find((task) => task.record_id === id).deleted, 1);
    assert.equal(tasks().filter((task) => task.deleted === 0).length, 1);
    await page.getByTestId("captured-todo").getByRole("button", { name: "另一个任务", exact: true }).click();
    await details().getByRole("button", { name: "删除任务", exact: true }).click();
    database((db) => db.exec("CREATE TRIGGER fail_delete_window BEFORE INSERT ON pending_operations WHEN NEW.kind = 'delete' BEGIN SELECT RAISE(ABORT, 'delete failure'); END"));
    await details().getByRole("button", { name: "确认删除任务", exact: true }).click();
    await details().getByTestId("todo-progress-status").getByText(/本机保存失败/).waitFor();
    assert.equal(tasks().filter((task) => task.deleted === 0).length, 1);
    database((db) => db.exec("DROP TRIGGER fail_delete_window"));
    await details().getByRole("button", { name: "取消删除", exact: true }).click();
    await details().getByRole("button", { name: "关闭详情", exact: true }).click();
    await page.screenshot({ path: ".build/todo-progression.png", fullPage: true });
    await application.close(); application = undefined;
    application = await launch(); page = await application.firstWindow();
    await page.getByTestId("captured-todo").getByRole("button", { name: "另一个任务", exact: true }).waitFor();
    assert.equal(await page.locator('[data-record-id="' + id + '"]').count(), 0);
    assert.equal(await page.getByRole("button", { name: "撤销删除", exact: true }).count(), 0);
  } catch (error) {
    if (application) { const page=await application.firstWindow(); console.log("progress failure",await page.locator("body").innerText()); await page.screenshot({path:".build/todo-progress-failure.png",fullPage:true}).catch(()=>undefined); }
    throw error;
  } finally {
    if (application) await application.close();
    assert.equal(dirname(resolve(directory)), resolve(tmpdir()));
    assert.ok(directory.split(/[/\\]/).at(-1)?.startsWith("workspace-progress-window-"));
    rmSync(directory, { recursive: true, force: true });
  }
});
